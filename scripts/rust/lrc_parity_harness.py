#!/usr/bin/env python3
"""Generates the Kotlin half of the Kotlin<->Rust LRC parity harness.

The Kotlin parser and the HTML-entity decoder are EXTRACTED FROM THE REPOSITORY at the commit
under test rather than copied by hand, so the oracle can never drift from the shipped code.
Used by `scripts/rust/verify-lrc-parity.sh`; prints Harness.kt to stdout.
"""

from __future__ import annotations

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]

PARSER = ROOT / "core/service/lyricsService/src/commonMain/kotlin/org/simpmusic/lyrics/parser/LrcTextParser.kt"
EXTENSIONS = ROOT / "core/domain/src/commonMain/kotlin/com/maxrave/domain/extension/AllExt.kt"


def extract(path: pathlib.Path, start_marker: str) -> str:
    """Returns the source of a top-level function, from its signature to its closing brace."""
    src = path.read_text(encoding="utf-8") + "\n"
    start = src.index(start_marker)
    cursor = src.index("\n", start)
    while True:
        line_end = src.index("\n", cursor + 1)
        if src[cursor + 1 : line_end] == "}":
            return src[start : line_end + 1]
        cursor = line_end


HEADER = """// GENERATED by scripts/rust/lrc_parity_harness.py — do not edit.
// Both functions below are extracted verbatim from the repository at the commit under test.
package harness

import com.maxrave.earixrust.LrcLine
import com.maxrave.earixrust.coreVersion
import com.maxrave.earixrust.parseLrcLines
import java.nio.file.Files
import java.nio.file.Path

data class ParsedLrcLine(val startTimeMs: Long, val text: String)

"""

BODY = r'''
fun esc(s: String): String =
    s.replace("\\", "\\\\").replace("\t", "\\t").replace("\n", "\\n").replace("\r", "\\r")

fun canonKotlin(doc: String): String =
    parseSyncedLrcLinesKotlin(doc).joinToString("") { l -> l.startTimeMs.toString() + "\t" + esc(l.text) + "\n" }

fun canonRust(doc: String): String =
    parseLrcLines(doc).joinToString("") { l: LrcLine -> l.startTimeMs.toString() + "\t" + esc(l.text) + "\n" }

fun check(name: String, doc: String) {
    val k = canonKotlin(doc)
    val r = canonRust(doc)
    if (k == r) {
        println("EQUIVALENT  " + name + "  lines=" + parseSyncedLrcLinesKotlin(doc).size)
    } else {
        println("MISMATCH    " + name)
        println("--- kotlin ---")
        print(k)
        println("--- rust ---")
        print(r)
        System.exit(1)
    }
}

fun timeKotlin(doc: String, iters: Int): Long {
    val t0 = System.nanoTime()
    var sink = 0
    repeat(iters) { sink += parseSyncedLrcLinesKotlin(doc).size }
    val dt = System.nanoTime() - t0
    if (sink < 0) println("impossible")
    return dt
}

fun timeRust(doc: String, iters: Int): Long {
    val t0 = System.nanoTime()
    var sink = 0
    repeat(iters) { sink += parseLrcLines(doc).size }
    val dt = System.nanoTime() - t0
    if (sink < 0) println("impossible")
    return dt
}

fun main(args: Array<String>) {
    println("rust core version=" + coreVersion())
    when (args[0]) {
        "equiv" -> {
            check("empty", "")
            check("whitespace", "   \n\t \r\n ")
            check("malformed", "[0:00.00]short\n[00:00.000]wide\n[00:00:00]bad\nno timestamp\n[00:00.00]")
            check("crlf", "[00:01.00]a\r\n[00:02.00]b\r[00:03.00]c")
            check("unicode", "[00:09.99]\u65e5\u672c\u8a9e \ud83c\udfb5 &amp; &#39;\n[00:10.00]\u0623\u0647\u0644\u0627")
            check("blank-content", "[00:05.00]   \n[00:06.00]next")
            check("final-blank-dropped", "[00:05.00]x\n[00:06.00]   ")
            check("figure-space", "[00:01.00]\u2007\n[00:02.00]next")
            check("line-sep-u2028", "[00:01.00]a\u2028b")
            check("entities", "[00:01.00]&amp; &quot;x&quot; &#39;y&#39; &#x27;z&#x27;")
            check("long", Files.readString(Path.of(args[1])))
            println("ALL EQUIVALENT")
        }
        "bench" -> {
            val doc = Files.readString(Path.of(args[1]))
            val iters = args[2].toInt()
            repeat(5) {
                timeKotlin(doc, iters / 10)
                timeRust(doc, iters / 10)
            }
            val k = timeKotlin(doc, iters)
            val r = timeRust(doc, iters)
            val lines = parseSyncedLrcLinesKotlin(doc).size
            println("document_bytes=" + doc.length)
            println("parsed_lines=" + lines)
            println("iterations=" + iters)
            println("kotlin_total_ns=" + k)
            println("rust_total_ns=" + r)
            println("kotlin_ns_per_doc=" + (k.toDouble() / iters))
            println("rust_ns_per_doc=" + (r.toDouble() / iters))
            println("speedup_kotlin_over_rust=" + (k.toDouble() / r.toDouble()))
            println("kotlin_lines_per_sec=" + (lines.toDouble() * iters / (k / 1e9)))
            println("rust_lines_per_sec=" + (lines.toDouble() * iters / (r / 1e9)))
        }
        else -> error("unknown mode")
    }
}
'''


def main() -> int:
    kotlin_fn = extract(PARSER, "internal fun parseSyncedLrcLinesKotlin").replace("internal fun ", "fun ", 1)
    decode_fn = extract(EXTENSIONS, "fun decodeHtmlEntities")
    sys.stdout.write(HEADER + kotlin_fn + "\n" + decode_fn + BODY)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
